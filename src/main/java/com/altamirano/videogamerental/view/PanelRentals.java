    private void buttonReturnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonReturnActionPerformed
        // TODO add your handling code here:

        //Compruebe que haya una fila seleccionada
        int fila = tableRentals.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Seleccione un alquiler para devolver"
            );
            return;
        }

        //Recuperamos el numero de registro de la fila seleccionada
        int filaModelo = tableRentals.convertRowIndexToModel(fila);

        int numberId = (int) tableRentals.getModel().getValueAt(filaModelo, 0);

        //Buscamos el objeto
        Rental rental = null;

        for (Rental r : rentalController.getRentals()) {
            if (r.getNumberId() == numberId) {
                rental = r;
                break;
            }
        }

        //Confirmacion de devolucion
        int respuesta = JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de que desea devolver este juego?",
                "Confirmar devolución",
                JOptionPane.YES_NO_OPTION
        );

        if (respuesta != JOptionPane.YES_OPTION) {
            return;
        }

        //Ejecutamos la devolucion con un Try-Catch
        try {

            rentalController.returnRental(rental);

            JOptionPane.showMessageDialog(
                    this,
                    "Juego devuelto correctamente"
            );

            mainView.actualizarPantallas();

        } catch (ValidationException e) {

            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }

    }//GEN-LAST:event_buttonReturnActionPerformed

