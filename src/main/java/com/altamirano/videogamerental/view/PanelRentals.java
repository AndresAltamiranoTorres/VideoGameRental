    /**
     * Creamos Metodo para cargar los alquileres
     */
    public void cargarRentals() {
        /**
         * Primero obtenemos el modelo de la tabla, que se encarga de gestionar
         * las filas y columnas
         */
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tableRentals.getModel();

        /**
         * Limpiamos la tabla para evitar duplicados para cuando se actualice
         */
        model.setRowCount(0);

        /**
         * Creamos For-Each para que nos saque los datos de cada Rental
         */
        for (Rental rental : rentalController.getRentals()) {

            /**
             * Añadimos los datos a la tabla con model.addRow()
             */
            model.addRow(new Object[]{
                rental.getNumberId(),
                rental.getUser().getName() + " " + rental.getUser().getLastname(),
                rental.getGame().getName(),
                rental.getPlatform(),
                rental.getDateStart(),
                rental.getDateEnd(),
                rental.getStatus()
            });

        }

    }

    /**
     * Metodo para actualizar los colores de la fila ACTIVE(VERDE) //
     * ROJO(RETURNED)
     */
    private void colorearFilas() {

        tableRentals.setDefaultRenderer(Object.class, new javax.swing.table.DefaultTableCellRenderer() {

            @Override
            public java.awt.Component getTableCellRendererComponent(
                    javax.swing.JTable table,
                    Object value,
                    boolean isSelected,
                    boolean hasFocus,
                    int row,
                    int column) {

                java.awt.Component c = super.getTableCellRendererComponent(
                        table, value, isSelected, hasFocus, row, column
                );

                int filaModelo = table.convertRowIndexToModel(row);

                Object estado = table.getModel().getValueAt(filaModelo, 6);

                if (estado != null && estado.toString().equals("ACTIVE")) {
                    c.setBackground(new java.awt.Color(198, 239, 206));
                    c.setForeground(java.awt.Color.BLACK);

                } else if (estado != null && estado.toString().equals("RETURNED")) {
                    c.setBackground(new java.awt.Color(255, 199, 206));
                    c.setForeground(java.awt.Color.BLACK);

                }

                if (isSelected) {
                    c.setBackground(table.getSelectionBackground());
                    c.setForeground(table.getSelectionForeground());
                }

                return c;
            }
        });
    }

