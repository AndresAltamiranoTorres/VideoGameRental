    private void buttonAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonAddActionPerformed
        // TODO add your handling code here:

        try {

            /**
             * Obtenemos los datos de las Fields
             */
            String name = fieldName.getText();
            String lastname = fieldLastname.getText();
            String surname = fieldSurname.getText();
            String dni = fieldDni.getText();
            String phone = fieldPhone.getText();

            /**
             * Creamos el nuevo usuario usando el metodo del controllador
             */
            userController.newUser(
                    name,
                    lastname,
                    surname,
                    dni,
                    phone
            );

            /**
             * Creamos un mini JDialog para saber que se ha añadido el usuario
             */
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Usuario creado correctamente"
            );

            // Cerramos el Dialog
            this.dispose();

        } catch (ValidationException e) {

            /**
             * Creamos un Jdialog que nos dice si hubo un error en la creacion
             */
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );

        }


    }//GEN-LAST:event_buttonAddActionPerformed


