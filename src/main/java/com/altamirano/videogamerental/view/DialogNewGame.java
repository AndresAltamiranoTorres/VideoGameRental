    private void buttonAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonAddActionPerformed
        // TODO add your handling code here:

        try {

            /**
             * Obtenemos los valores del nombre, la lista del combo Box
             * plataforma y stock.
             */
            String name = fieldNameGame.getText();
            Genre genre = (Genre) comboBoxGenre.getSelectedItem();
            List<PlatformStock> platforms = new ArrayList<>();

            /**
             * Condicional de solo añadir si el checBox esta seleccionado. Si el
             * CheckBox esta selecionado, agregamos a la lista<plataforms>
             * un nuevo objeto, la plataforma (PS,XBOX,PC,SWITCH) con el valor
             * dado en el Value.
             *
             * Tambien tiene una condicional de que si el Stock es mayor a 0 se
             * guarde
             */
            if (checkBoxPs5.isSelected()) {
                int stock = (Integer) spinnerPs5.getValue();

                if (stock > 0) {
                    platforms.add(new PlatformStock(Platform.PS5, stock));
                }
            }

            if (checkBoxXbox.isSelected()) {
                int stock = (Integer) spinnerXbox.getValue();

                if (stock > 0) {
                    platforms.add(new PlatformStock(Platform.XBOX, stock));
                }
            }

            if (checkBoxPc.isSelected()) {
                int stock = (Integer) spinnerPc.getValue();

                if (stock > 0) {
                    platforms.add(new PlatformStock(Platform.PC, stock));
                }
            }

            if (checkBoxSwitch.isSelected()) {
                int stock = (Integer) spinnerSwitch.getValue();

                if (stock > 0) {
                    platforms.add(new PlatformStock(Platform.SWITCH_2, stock));
                }
            }

            /**
             * Obtenidos todos los datos añadimos el juego
             */
            gameController.newGame(name, genre, platforms);

            //Monstramos un dialogo que se ha creado correctamente
            JOptionPane.showMessageDialog(
                    this,
                    "Juego creado correctamente"
            );

            //Cerrramos la ventana
            this.dispose();

        } catch (ValidationException e) {

            /**
             * Creamos JDIALOG para monstrar algun error
             */
            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_buttonAddActionPerformed


